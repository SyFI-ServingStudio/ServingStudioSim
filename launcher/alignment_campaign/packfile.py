"""Write a pack's `campaign.yaml` the way every generator should.

Generated packs are long because block-style YAML puts each list item on its own
line. A DeepSeek-V4.1 pack spent most of its 2,525 lines on two kinds of list:
the numeric strings after `--cudagraph-capture-sizes` in a server's `extra_args`,
and the `[input_len, output_len]` pairs of a trace's `shapes`.

The rule here is one test on the value, not a list of keys: a list whose items
are all scalars, or all such lists, is written in flow style (`[1, 2, 4]`,
`[[1024, 32], [2048, 64]]`); mappings and lists of mappings stay block style.
That covers `extra_args` without naming it — its flags and its capture sizes are
all strings. A long flow list wraps at `width`, so a line stays readable.

Only the layout changes. `yaml.safe_load` of the output equals the document
that was dumped; `tests/test_alignment_campaign_packfile.py` holds that.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

GENERATED_HEADER = "# Generated by make_pack.py; edit that, not this.\n"

_SCALARS = (str, int, float, bool, type(None))


def _flat(items: list[Any]) -> bool:
    return all(isinstance(item, _SCALARS) for item in items)


def _flow_list(items: list[Any]) -> bool:
    """All scalars, or all non-empty lists of scalars."""
    if _flat(items):
        return True
    return all(isinstance(item, list) and _flat(item) for item in items)


class _PackDumper(yaml.SafeDumper):
    pass


def _represent_list(dumper: yaml.SafeDumper, data: list[Any]) -> yaml.Node:
    return dumper.represent_sequence(
        "tag:yaml.org,2002:seq", data, flow_style=True if _flow_list(data) else False
    )


_PackDumper.add_representer(list, _represent_list)
_PackDumper.add_representer(tuple, _represent_list)


def dump_campaign(document: dict[str, Any], *, width: int = 110) -> str:
    """The YAML text of one campaign document, keys in authored order."""
    return yaml.dump(
        document,
        Dumper=_PackDumper,
        sort_keys=False,
        default_flow_style=False,
        width=width,
        allow_unicode=False,
    )


def write_campaign(
    path: Path, document: dict[str, Any], *, header: str = GENERATED_HEADER, width: int = 110
) -> Path:
    """Write `document` to `path` behind the generated-file header."""
    path = Path(path)
    path.write_text(header + dump_campaign(document, width=width))
    return path
